'use client';

import React, { useState } from 'react';
import { useProfile, Medication } from '@/contexts/ProfileContext';
import {
  Pill,
  Plus,
  Trash2,
  AlertTriangle,
  Sparkles,
  Camera,
  CheckCircle,
  Clock,
  ShieldAlert,
  Info,
  Calendar,
  X,
  RefreshCw,
  Search,
} from 'lucide-react';

export default function MedicationsPage() {
  const { medications, addMedication, deleteMedication, activeProfile } = useProfile();

  const [isAddOpen, setIsAddOpen] = useState(false);
  const [isAiCheckerOpen, setIsAiCheckerOpen] = useState(false);
  const [isScanOpen, setIsScanOpen] = useState(false);
  const [aiChecking, setAiChecking] = useState(false);
  const [aiAnalysisResult, setAiAnalysisResult] = useState<string | null>(null);

  // Form states for new medication
  const [name, setName] = useState('');
  const [dosage, setDosage] = useState('');
  const [unit, setUnit] = useState('mg');
  const [frequency, setFrequency] = useState<Medication['frequency']>('daily');
  const [time1, setTime1] = useState('08:00');
  const [time2, setTime2] = useState('20:00');
  const [instructions, setInstructions] = useState('');
  const [refillCount, setRefillCount] = useState(30);

  // Scan states
  const [scanImage, setScanImage] = useState<string | null>(null);
  const [isScanning, setIsScanning] = useState(false);

  const handleAddSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!name || !dosage) return;

    const times = frequency === 'twice_daily' ? [time1, time2] : [time1];

    await addMedication({
      name,
      dosage,
      unit,
      frequency,
      times,
      instructions: instructions || 'Take as prescribed by physician.',
      startDate: new Date().toISOString().split('T')[0],
      refillCount: Number(refillCount) || 30,
      refillAlertAt: Math.ceil((Number(refillCount) || 30) * 0.2),
      color: '#2563EB',
    });

    setIsAddOpen(false);
    // Reset form
    setName('');
    setDosage('');
    setInstructions('');
  };

  const handleRunAiInteractionCheck = async () => {
    setIsAiCheckerOpen(true);
    setAiChecking(true);
    setAiAnalysisResult(null);

    // Simulated Gemini Clinical Pharmacist Analysis
    setTimeout(() => {
      const medNames = medications.map((m) => `${m.name} (${m.dosage}${m.unit})`).join(', ');
      setAiAnalysisResult(`### 🩺 Gemini Clinical Pharmacist Report for ${activeProfile?.name || 'Patient'}
**Medications Reviewed:** ${medNames}

#### 1. Drug-Drug Interactions
- **Metformin + Lisinopril:** ✅ **Low Risk / Safe Combination**. Commonly co-prescribed for patients with hypertension and type 2 diabetes. No direct adverse biochemical interaction detected.
- **Atorvastatin + Lisinopril:** ✅ **Safe**. Maintain regular routine liver function and kidney tests as per annual doctor visits.

#### 2. Food & Drink Guidelines
- ⚠️ **Grapefruit Warning:** Avoid large amounts of grapefruit juice while taking Atorvastatin, as it can increase statin concentration in blood.
- 🍽️ **Meal Timing:** Always take Metformin **with or immediately after meals** to minimize stomach upset.
- 💧 **Hydration:** Take Lisinopril with a full glass of water in the morning to maintain optimal renal perfusion.

#### 3. Senior Safety Recommendation
- Check blood pressure regularly, particularly when standing quickly (orthostatic hypotension risk with Lisinopril).
- *Disclaimer: AI report generated by CareSync Gemini 1.5 Flash. Consult your physician for medical decisions.*`);
      setAiChecking(false);
    }, 1500);
  };

  const handleSimulatePrescriptionScan = () => {
    setIsScanning(true);
    setTimeout(() => {
      setIsScanning(false);
      setName('Amlodipine Besylate');
      setDosage('5');
      setUnit('mg');
      setFrequency('daily');
      setTime1('09:00');
      setInstructions('Take once daily in the morning for blood pressure control.');
      setRefillCount(30);
      setIsScanOpen(false);
      setIsAddOpen(true);
    }, 1800);
  };

  return (
    <div className="space-y-8 animate-in fade-in">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-3xl font-black text-slate-900 tracking-tight flex items-center gap-3">
            <Pill className="w-8 h-8 text-blue-600" />
            Medication Management
          </h1>
          <p className="text-slate-600 text-lg mt-1">
            Active prescriptions, dosage schedules &amp; refill alerts for {activeProfile?.name}.
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-3">
          <button
            type="button"
            onClick={() => setIsScanOpen(true)}
            className="bg-purple-50 hover:bg-purple-100 text-purple-700 font-bold px-4 py-3 rounded-2xl border border-purple-200 flex items-center gap-2 text-base transition-colors"
          >
            <Camera className="w-5 h-5 text-purple-600" />
            <span>Scan Rx Label</span>
          </button>

          <button
            type="button"
            onClick={handleRunAiInteractionCheck}
            className="bg-teal-50 hover:bg-teal-100 text-teal-800 font-bold px-4 py-3 rounded-2xl border border-teal-200 flex items-center gap-2 text-base transition-colors"
          >
            <Sparkles className="w-5 h-5 text-teal-600" />
            <span>AI Interaction Check</span>
          </button>

          <button
            type="button"
            onClick={() => setIsAddOpen(true)}
            className="bg-blue-600 hover:bg-blue-700 text-white font-extrabold px-5 py-3 rounded-2xl shadow-md shadow-blue-600/20 flex items-center gap-2 text-base transition-all cursor-pointer"
          >
            <Plus className="w-5 h-5" />
            <span>Add Medication</span>
          </button>
        </div>
      </div>

      {/* Grid of Medications */}
      <div className="grid md:grid-cols-2 lg:grid-cols-3 gap-6">
        {medications.map((med) => {
          const isLowRefill = med.refillCount <= med.refillAlertAt;
          return (
            <div
              key={med.id}
              className="bg-white rounded-3xl p-6 border-2 border-slate-200/80 shadow-xs hover:border-blue-400 transition-all flex flex-col justify-between"
            >
              <div>
                <div className="flex items-start justify-between gap-3 mb-3">
                  <div>
                    <h3 className="text-2xl font-black text-slate-900">{med.name}</h3>
                    <div className="inline-flex items-center gap-1.5 mt-1">
                      <span className="text-base font-bold bg-blue-50 text-blue-700 px-2.5 py-0.5 rounded-lg border border-blue-200">
                        {med.dosage} {med.unit}
                      </span>
                      <span className="text-xs uppercase font-bold text-slate-500 bg-slate-100 px-2 py-1 rounded-md">
                        {med.frequency.replace('_', ' ')}
                      </span>
                    </div>
                  </div>

                  <button
                    type="button"
                    onClick={() => deleteMedication(med.id)}
                    className="p-2 text-slate-400 hover:text-rose-600 rounded-xl hover:bg-rose-50 transition-colors"
                    title="Remove medication"
                  >
                    <Trash2 className="w-5 h-5" />
                  </button>
                </div>

                <div className="space-y-2 mt-4 text-sm text-slate-600">
                  <div className="flex items-center gap-2">
                    <Clock className="w-4 h-4 text-blue-600" />
                    <span className="font-semibold text-slate-800">Times:</span>
                    <span>{med.times.join(', ')}</span>
                  </div>

                  <p className="bg-slate-50 p-3 rounded-xl border border-slate-100 text-slate-700 font-medium">
                    {med.instructions || 'Take as instructed.'}
                  </p>
                </div>
              </div>

              {/* Refill Status Bar */}
              <div className="mt-6 pt-4 border-t border-slate-100 flex items-center justify-between">
                <div>
                  <span className="text-xs font-bold text-slate-400 uppercase">Pills Remaining</span>
                  <div className={`text-lg font-black ${isLowRefill ? 'text-rose-600' : 'text-slate-900'}`}>
                    {med.refillCount} pills
                  </div>
                </div>

                {isLowRefill ? (
                  <span className="inline-flex items-center gap-1 bg-rose-100 text-rose-800 text-xs font-bold px-2.5 py-1 rounded-full">
                    <AlertTriangle className="w-3.5 h-3.5" />
                    Low Supply!
                  </span>
                ) : (
                  <span className="text-xs text-emerald-700 font-bold bg-emerald-50 px-2 py-1 rounded-md">
                    Supply OK
                  </span>
                )}
              </div>
            </div>
          );
        })}
      </div>

      {/* Add Medication Modal */}
      {isAddOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-900/60 backdrop-blur-xs p-4 animate-in fade-in">
          <div className="bg-white rounded-3xl max-w-lg w-full p-8 shadow-2xl border border-slate-100 max-h-[90vh] overflow-y-auto">
            <div className="flex items-center justify-between mb-6">
              <h2 className="text-2xl font-black text-slate-900 flex items-center gap-2">
                <Pill className="w-6 h-6 text-blue-600" />
                Add New Medication
              </h2>
              <button onClick={() => setIsAddOpen(false)} className="p-2 text-slate-400 hover:text-slate-600">
                <X className="w-6 h-6" />
              </button>
            </div>

            <form onSubmit={handleAddSubmit} className="space-y-4">
              <div>
                <label className="block text-sm font-bold text-slate-700 mb-1">Medication Name</label>
                <input
                  type="text"
                  required
                  value={name}
                  onChange={(e) => setName(e.target.value)}
                  placeholder="e.g. Metformin, Lisinopril"
                  className="w-full px-4 py-3 rounded-xl border-2 border-slate-200 text-lg font-medium focus:outline-none focus:border-blue-600"
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-sm font-bold text-slate-700 mb-1">Dosage</label>
                  <input
                    type="text"
                    required
                    value={dosage}
                    onChange={(e) => setDosage(e.target.value)}
                    placeholder="e.g. 500, 10"
                    className="w-full px-4 py-3 rounded-xl border-2 border-slate-200 text-lg font-medium focus:outline-none focus:border-blue-600"
                  />
                </div>
                <div>
                  <label className="block text-sm font-bold text-slate-700 mb-1">Unit</label>
                  <select
                    value={unit}
                    onChange={(e) => setUnit(e.target.value)}
                    className="w-full px-4 py-3 rounded-xl border-2 border-slate-200 text-lg font-medium focus:outline-none focus:border-blue-600 bg-white"
                  >
                    <option value="mg">mg</option>
                    <option value="mcg">mcg</option>
                    <option value="g">g</option>
                    <option value="ml">ml</option>
                    <option value="IU">IU</option>
                    <option value="drops">drops</option>
                  </select>
                </div>
              </div>

              <div>
                <label className="block text-sm font-bold text-slate-700 mb-1">Frequency</label>
                <select
                  value={frequency}
                  onChange={(e) => setFrequency(e.target.value as Medication['frequency'])}
                  className="w-full px-4 py-3 rounded-xl border-2 border-slate-200 text-lg font-medium focus:outline-none focus:border-blue-600 bg-white"
                >
                  <option value="daily">Once Daily</option>
                  <option value="twice_daily">Twice Daily</option>
                  <option value="three_times">Three Times Daily</option>
                  <option value="as_needed">As Needed (PRN)</option>
                  <option value="weekly">Weekly</option>
                </select>
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-sm font-bold text-slate-700 mb-1">Dose Time 1</label>
                  <input
                    type="time"
                    value={time1}
                    onChange={(e) => setTime1(e.target.value)}
                    className="w-full px-4 py-3 rounded-xl border-2 border-slate-200 font-medium"
                  />
                </div>
                {frequency === 'twice_daily' && (
                  <div>
                    <label className="block text-sm font-bold text-slate-700 mb-1">Dose Time 2</label>
                    <input
                      type="time"
                      value={time2}
                      onChange={(e) => setTime2(e.target.value)}
                      className="w-full px-4 py-3 rounded-xl border-2 border-slate-200 font-medium"
                    />
                  </div>
                )}
              </div>

              <div>
                <label className="block text-sm font-bold text-slate-700 mb-1">Special Instructions</label>
                <input
                  type="text"
                  value={instructions}
                  onChange={(e) => setInstructions(e.target.value)}
                  placeholder="e.g. Take with breakfast"
                  className="w-full px-4 py-3 rounded-xl border-2 border-slate-200 font-medium"
                />
              </div>

              <div>
                <label className="block text-sm font-bold text-slate-700 mb-1">Current Pill Count (for refill alerts)</label>
                <input
                  type="number"
                  value={refillCount}
                  onChange={(e) => setRefillCount(Number(e.target.value))}
                  className="w-full px-4 py-3 rounded-xl border-2 border-slate-200 font-medium"
                />
              </div>

              <div className="pt-4 flex gap-3">
                <button
                  type="button"
                  onClick={() => setIsAddOpen(false)}
                  className="flex-1 bg-slate-100 hover:bg-slate-200 text-slate-700 font-bold py-3.5 rounded-xl transition-colors"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  className="flex-1 bg-blue-600 hover:bg-blue-700 text-white font-bold py-3.5 rounded-xl transition-all shadow-md shadow-blue-500/20"
                >
                  Save Schedule
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* AI Interaction Check Modal */}
      {isAiCheckerOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-900/60 backdrop-blur-xs p-4 animate-in fade-in">
          <div className="bg-white rounded-3xl max-w-2xl w-full p-8 shadow-2xl border border-slate-100 max-h-[85vh] overflow-y-auto">
            <div className="flex items-center justify-between mb-4 pb-3 border-b border-slate-100">
              <div className="flex items-center gap-2 text-teal-700 font-black text-2xl">
                <Sparkles className="w-7 h-7" />
                <span>Gemini Drug Interaction Analysis</span>
              </div>
              <button onClick={() => setIsAiCheckerOpen(false)} className="p-2 text-slate-400 hover:text-slate-600">
                <X className="w-6 h-6" />
              </button>
            </div>

            {aiChecking ? (
              <div className="text-center py-12">
                <div className="w-16 h-16 border-4 border-teal-500 border-t-transparent rounded-full animate-spin mx-auto mb-4" />
                <h3 className="text-xl font-bold text-slate-800">Reviewing All Active Prescriptions...</h3>
                <p className="text-slate-500 mt-1">Cross-referencing drug combinations with Gemini 1.5 Flash</p>
              </div>
            ) : (
              <div className="prose prose-slate max-w-none text-slate-800 text-base leading-relaxed whitespace-pre-line">
                {aiAnalysisResult}
              </div>
            )}

            <div className="mt-8 pt-4 border-t border-slate-100 flex justify-end">
              <button
                type="button"
                onClick={() => setIsAiCheckerOpen(false)}
                className="bg-slate-900 text-white font-bold px-6 py-3 rounded-xl hover:bg-slate-800 transition-colors"
              >
                Close Report
              </button>
            </div>
          </div>
        </div>
      )}

      {/* Gemini Vision Prescription Scanner Modal */}
      {isScanOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-900/60 backdrop-blur-xs p-4 animate-in fade-in">
          <div className="bg-white rounded-3xl max-w-lg w-full p-8 shadow-2xl border border-slate-100">
            <div className="flex items-center justify-between mb-4">
              <div className="flex items-center gap-2 text-purple-700 font-black text-2xl">
                <Camera className="w-7 h-7" />
                <span>Scan Prescription / Bottle</span>
              </div>
              <button onClick={() => setIsScanOpen(false)} className="p-2 text-slate-400 hover:text-slate-600">
                <X className="w-6 h-6" />
              </button>
            </div>

            <p className="text-slate-600 text-base mb-6">
              Upload a picture of your prescription label. Gemini Vision AI will automatically extract the medicine name, dosage, and intake directions!
            </p>

            <div className="border-2 border-dashed border-purple-200 rounded-2xl p-8 text-center bg-purple-50/50 mb-6">
              <Camera className="w-12 h-12 text-purple-400 mx-auto mb-2" />
              <p className="font-bold text-slate-700">Drop prescription photo here or click to browse</p>
              <p className="text-xs text-slate-400 mt-1">Supports PNG, JPG, or pillbox photo</p>
            </div>

            <button
              type="button"
              disabled={isScanning}
              onClick={handleSimulatePrescriptionScan}
              className="w-full bg-purple-600 hover:bg-purple-700 text-white font-extrabold py-4 rounded-xl text-lg flex items-center justify-center gap-2 shadow-md shadow-purple-600/25 transition-all cursor-pointer"
            >
              {isScanning ? (
                <>
                  <RefreshCw className="w-5 h-5 animate-spin" />
                  <span>Gemini Vision AI Extracting...</span>
                </>
              ) : (
                <>
                  <Sparkles className="w-5 h-5" />
                  <span>Scan Sample Label &amp; Auto-Fill</span>
                </>
              )}
            </button>
          </div>
        </div>
      )}
    </div>
  );
}
